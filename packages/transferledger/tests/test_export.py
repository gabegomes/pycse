"""Taking an equation out of the package."""

import json

import numpy as np
import pandas as pd
import pytest

from transferledger import PieceModel
from transferledger.assemble import evaluate
from transferledger.forms import sigmoid


@pytest.fixture(scope="module")
def fitted():
    rng = np.random.default_rng(0)
    n = 400
    X = pd.DataFrame({
        "dose": rng.uniform(0, 10, n), "temp": rng.uniform(15, 35, n), "energy": rng.uniform(-30, 0, n),
        "who": rng.choice(["ana", "ben", "cy"], n),
    })  # fmt: skip
    s = sigmoid((X.dose - 6.0) / 0.4)
    y = (2.0 * s - 0.08 * X.temp * (1 - 0.8 * s) - 0.01 * (X.energy + 15) ** 2
         + 0.6 * (X.who == "ben") + 0.1 * rng.normal(size=n))  # fmt: skip
    return PieceModel().fit(X, y), X, y.to_numpy()


def test_dictionary_round_trip_predicts_the_same(fitted, tmp_path):
    m, X, _ = fitted
    d = json.loads(json.dumps(m.to_dict()))
    again = PieceModel.from_dict(d)
    assert np.allclose(again.predict(X), m.predict(X))
    assert again.equation() == m.equation()
    m.save(tmp_path / "equation.json")
    loaded = PieceModel.load(tmp_path / "equation.json")
    assert np.allclose(loaded.predict(X), m.predict(X))
    far = loaded.support(X.head(3).assign(dose=50.0))
    assert (far.outside >= 1).all() and far.distance.isna().all()


def test_python_source_reproduces_predict_without_the_package(fitted):
    m, X, _ = fitted
    src = m.to_python("f")
    assert "transferledger" not in src.replace("generated by transferledger", "")
    scope = {}
    exec(src, scope)
    assert np.allclose(scope["f"](X), m.predict(X))
    assert np.allclose(scope["f"]({c: X[c].to_numpy() for c in X}), m.predict(X))


def test_sympy_matches_inside_the_fitted_range(fitted):
    sp = pytest.importorskip("sympy")
    _, X, y = fitted
    num = X.drop(columns="who")
    m = PieceModel().fit(num, y)
    expr, syms = m.to_sympy()
    names = [c for c in num.columns if c in syms]
    f = sp.lambdify([syms[c] for c in names], expr, "numpy")
    assert np.allclose(f(*[num[c].to_numpy() for c in names]), m.decision_function(num), atol=1e-6)


def test_latex_names_every_piece(fitted):
    m, _, _ = fitted
    tex = m.to_latex()
    assert tex.count("&=") == len(m.chosen_) + 1 and "\\mathrm{dose}" in tex


def test_expression_evaluator_does_arithmetic_only():
    v = {"p0": np.array([1.0, 2.0]), "p1": np.array([3.0, 4.0])}
    assert np.allclose(
        evaluate("p0*(0.5 - p1) + p0**2", v), v["p0"] * (0.5 - v["p1"]) + v["p0"] ** 2
    )
    for bad in ["__import__('os')", "p0.real", "p2 + 1", "abs(p0)", "p0 ** p1"]:
        with pytest.raises(ValueError):
            evaluate(bad, v)


@pytest.mark.slow
def test_pysr_assembler_finds_a_switching_slope():
    pytest.importorskip("pysr")
    rng = np.random.default_rng(1)
    n = 500
    X = pd.DataFrame({"s": rng.normal(size=n), "v": rng.uniform(22, 50, n)})
    step = sigmoid(X.v - 32.0)
    y = (2.0 - 2.5 * step) * X.s - 1.5 * step + 0.1 * rng.normal(size=n)
    m = PieceModel(products="pysr", pysr_options={"niterations": 30}).fit(X, y)
    assert m.expression_ is not None and "g" in m.equation()
    assert np.corrcoef(m.predict(X), y)[0, 1] > 0.98
    again = PieceModel.from_dict(m.to_dict())
    assert np.allclose(again.predict(X), m.predict(X))
